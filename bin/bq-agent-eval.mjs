#!/usr/bin/env node

import { spawn, spawnSync } from "node:child_process";
import { access, copyFile, readFile, writeFile } from "node:fs/promises";
import { constants } from "node:fs";
import { homedir } from "node:os";
import path from "node:path";
import process from "node:process";
import { createInterface } from "node:readline/promises";
import { fileURLToPath, pathToFileURL } from "node:url";

const rootDirectory = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const envPath = path.join(rootDirectory, ".env");
const envExamplePath = path.join(rootDirectory, ".env.example");
const skillPath = path.join(rootDirectory, "skills", "bq-data-agent-eval", "SKILL.md");
const PROJECT_PATTERN = /^[a-z][a-z0-9-]{4,61}[a-z0-9]$/;
const AGENT_PATTERN = /^projects\/([^/]+)\/locations\/([^/]+)\/dataAgents\/([^/]+)$/;

export function parseArgs(argv) {
  const result = { command: "help", flags: {} };
  const args = [...argv];
  if (args[0] && !args[0].startsWith("-")) result.command = args.shift();
  for (let index = 0; index < args.length; index += 1) {
    const value = args[index];
    if (!value.startsWith("--")) continue;
    const [rawKey, inlineValue] = value.slice(2).split("=", 2);
    if (inlineValue !== undefined) {
      result.flags[rawKey] = inlineValue;
    } else if (args[index + 1] && !args[index + 1].startsWith("--")) {
      result.flags[rawKey] = args[index + 1];
      index += 1;
    } else {
      result.flags[rawKey] = true;
    }
  }
  return result;
}

export function validateProjectId(value) {
  const projectId = String(value || "").trim();
  if (!PROJECT_PATTERN.test(projectId)) {
    throw new Error("Google Cloud project ID is invalid.");
  }
  return projectId;
}

export function validateAgentResource(value, projectId) {
  const resource = String(value || "").trim();
  const match = resource.match(AGENT_PATTERN);
  if (!match) {
    throw new Error(
      "Data Agent resource must match projects/<project>/locations/<location>/dataAgents/<id>."
    );
  }
  if (projectId && match[1] !== projectId) {
    throw new Error("Data Agent resource project does not match the billing project.");
  }
  return resource;
}

export function serializeEnv(values) {
  const quote = (value) => `"${String(value).replaceAll("\\", "\\\\").replaceAll('"', '\\"')}"`;
  return [
    "# Generated by bq-agent-eval. This file may contain environment-specific identifiers.",
    "# Do not commit it.",
    `APP_PORT=${values.appPort}`,
    `GCLOUD_CONFIG_DIR=${quote(values.gcloudConfigDir)}`,
    "CONTAINER_ADC_PATH=/home/node/.config/gcloud/application_default_credentials.json",
    `BQ_AGENT_BILLING_PROJECT=${values.projectId}`,
    `GOOGLE_CLOUD_QUOTA_PROJECT=${values.projectId}`,
    `BQ_AGENT_LOCATION=${values.location}`,
    `BQ_AGENT_RESOURCE=${values.agentResource}`,
    `BQ_AGENT_LABEL=${quote(values.agentLabel)}`,
    `VERTEX_AI_PROJECT=${values.projectId}`,
    `VERTEX_AI_LOCATION=${values.vertexLocation}`,
    "VERTEX_AI_MODEL=gemini-2.5-flash",
    "VERTEX_AI_JUDGE_MODEL=gemini-2.5-flash-lite",
    ""
  ].join("\n");
}

function commandAvailable(command, args = ["--version"]) {
  const result = spawnSync(command, args, { stdio: "ignore", timeout: 30_000 });
  return result.status === 0;
}

async function fileExists(filePath) {
  try {
    await access(filePath, constants.F_OK);
    return true;
  } catch {
    return false;
  }
}

function parseEnv(text) {
  return Object.fromEntries(
    String(text)
      .split(/\r?\n/)
      .map((line) => line.trim())
      .filter((line) => line && !line.startsWith("#") && line.includes("="))
      .map((line) => {
        const index = line.indexOf("=");
        const key = line.slice(0, index);
        const raw = line.slice(index + 1).trim();
        const value =
          raw.startsWith('"') && raw.endsWith('"')
            ? raw.slice(1, -1).replaceAll('\\"', '"').replaceAll("\\\\", "\\")
            : raw;
        return [key, value];
      })
  );
}

async function promptValue(terminal, label, fallback = "") {
  const suffix = fallback ? ` [${fallback}]` : "";
  const answer = (await terminal.question(`${label}${suffix}: `)).trim();
  return answer || fallback;
}

async function initialize(flags) {
  const existing = await fileExists(envPath);
  if (existing && !flags.force) {
    throw new Error(".env already exists. Use --force to replace it.");
  }

  let terminal;
  const interactive = Boolean(process.stdin.isTTY && process.stdout.isTTY);
  if (interactive) terminal = createInterface({ input: process.stdin, output: process.stdout });
  try {
    const projectInput =
      flags.project ||
      (interactive ? await promptValue(terminal, "Google Cloud project ID") : "");
    const projectId = validateProjectId(projectInput);
    const location = String(
      flags.location ||
        (interactive ? await promptValue(terminal, "Data Agent location", "global") : "global")
    ).trim();
    const suggestedResource = `projects/${projectId}/locations/${location}/dataAgents/`;
    const agentResource = validateAgentResource(
      flags.agent ||
        (interactive
          ? await promptValue(terminal, "Data Agent resource name", suggestedResource)
          : ""),
      projectId
    );
    const agentLabel =
      flags.label ||
      (interactive ? await promptValue(terminal, "Display name", "My BigQuery Data Agent") : "My BigQuery Data Agent");
    const appPort = Number(flags.port || 4318);
    if (!Number.isInteger(appPort) || appPort < 1024 || appPort > 65535) {
      throw new Error("Port must be an integer between 1024 and 65535.");
    }
    const defaultGcloudDirectory =
      process.platform === "win32"
        ? path.join(process.env.APPDATA || homedir(), "gcloud")
        : path.join(homedir(), ".config", "gcloud");
    const gcloudConfigDir = path.resolve(
      flags["gcloud-config"] ||
        (interactive
          ? await promptValue(terminal, "gcloud config directory", defaultGcloudDirectory)
          : defaultGcloudDirectory)
    );
    const contents = serializeEnv({
      appPort,
      gcloudConfigDir,
      projectId,
      location,
      agentResource,
      agentLabel,
      vertexLocation: String(flags["vertex-location"] || "global")
    });
    if (existing) await copyFile(envPath, `${envPath}.backup`);
    await writeFile(envPath, contents, { encoding: "utf8", mode: 0o600 });
    console.log(`Created ${envPath}`);
    if (existing) console.log(`Backup: ${envPath}.backup`);
    console.log("Next: gcloud auth application-default login --scopes=https://www.googleapis.com/auth/cloud-platform,https://www.googleapis.com/auth/spreadsheets");
    console.log("Then: npm run setup -- doctor");
  } finally {
    terminal?.close();
  }
}

async function doctor(flags) {
  const checks = [];
  const major = Number(process.versions.node.split(".")[0]);
  checks.push({ name: "Node.js >= 20", ok: major >= 20, detail: process.version });
  checks.push({ name: "Docker", ok: commandAvailable("docker") });
  checks.push({ name: "Docker Compose", ok: commandAvailable("docker", ["compose", "version"]) });
  checks.push({ name: "Google Cloud CLI", ok: commandAvailable("gcloud") });
  checks.push({
    name: "Application Default Credentials",
    ok: commandAvailable("gcloud", ["auth", "application-default", "print-access-token"])
  });

  const envExists = await fileExists(envPath);
  checks.push({ name: ".env configuration", ok: envExists });
  if (envExists) {
    const values = parseEnv(await readFile(envPath, "utf8"));
    let projectOk = false;
    let resourceOk = false;
    try {
      const projectId = validateProjectId(values.BQ_AGENT_BILLING_PROJECT);
      projectOk = true;
      validateAgentResource(values.BQ_AGENT_RESOURCE, projectId);
      resourceOk = true;
    } catch {
      // Report each validation as a failed check below.
    }
    checks.push({ name: "Billing project", ok: projectOk });
    checks.push({ name: "Data Agent resource", ok: resourceOk });
  }

  if (flags.json) {
    console.log(JSON.stringify({ ok: checks.every((check) => check.ok), checks }, null, 2));
  } else {
    for (const check of checks) {
      console.log(`${check.ok ? "✓" : "×"} ${check.name}${check.detail ? ` (${check.detail})` : ""}`);
    }
  }
  if (checks.some((check) => !check.ok)) process.exitCode = 1;
}

async function start(flags) {
  const args = ["compose", "up", "--build"];
  if (flags.detach || flags.d) args.push("-d");
  const child = spawn("docker", args, { cwd: rootDirectory, stdio: "inherit" });
  const status = await new Promise((resolve) => child.on("exit", resolve));
  process.exitCode = Number(status || 0);
}

function printSkill() {
  console.log(skillPath);
  console.log("");
  console.log("Codex: copy or symlink the containing directory into ~/.codex/skills/");
  console.log("Other coding agents: instruct the agent to read this SKILL.md before changing the project.");
}

function printHelp() {
  console.log(`BigQuery Data Agent Eval setup CLI

Usage:
  bq-agent-eval init [--project ID --agent RESOURCE --label NAME] [--force]
  bq-agent-eval doctor [--json]
  bq-agent-eval up [--detach]
  bq-agent-eval skill

Repository usage:
  npm run setup -- init
  npm run setup -- doctor
  npm run setup -- up --detach

The CLI never stores access tokens or service-account keys.`);
}

export async function main(argv = process.argv.slice(2)) {
  const { command, flags } = parseArgs(argv);
  if (flags.help || command === "help") return printHelp();
  if (command === "init") return initialize(flags);
  if (command === "doctor") return doctor(flags);
  if (command === "up") return start(flags);
  if (command === "skill") return printSkill();
  throw new Error(`Unknown command: ${command}`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  main().catch((error) => {
    console.error(`Error: ${error.message}`);
    process.exitCode = 1;
  });
}
