export const SUPPORTED_LOCALES = Object.freeze(["ja", "en"]);

export function normalizeLocale(value) {
  const locale = String(value || "").trim().toLowerCase();
  if (locale === "ja" || locale.startsWith("ja-")) return "ja";
  if (locale === "en" || locale.startsWith("en-")) return "en";
  return null;
}

export function resolveLocale({ savedLocale, languages = [], language = "" } = {}) {
  const saved = normalizeLocale(savedLocale);
  if (saved) return saved;

  for (const candidate of [...languages, language]) {
    const locale = normalizeLocale(candidate);
    if (locale) return locale;
  }
  return "en";
}

export function interpolate(template, vars = {}) {
  const values = vars && typeof vars === "object" ? vars : {};
  return String(template ?? "").replace(/\{([A-Za-z0-9_]+)\}/g, (token, key) => {
    const value = values[key];
    return value === undefined || value === null ? token : String(value);
  });
}

export function selectLocalizedText(locale, ja, en, vars = {}) {
  const preferred = normalizeLocale(locale) === "ja" ? ja : en;
  const fallback = normalizeLocale(locale) === "ja" ? en : ja;
  return interpolate(preferred ?? fallback ?? "", vars);
}

