export function translateUiText(text, locale = "en") {
  if (text === null || text === undefined) return text;
  const source = String(text);
  const leading = source.match(/^\s*/)?.[0] || "";
  const trailing = source.match(/\s*$/)?.[0] || "";
  const value = source.slice(leading.length, source.length - trailing.length || undefined);
  const japanese = normalizeLocale(locale) === "ja";
  const exact = (japanese ? EN_TO_JA_UI : JA_TO_EN_UI).get(value);
  if (exact !== undefined) return `${leading}${exact}${trailing}`;

  for (const [jaPattern, enReplacement, enPattern, jaReplacement] of UI_DYNAMIC_RULES) {
    const pattern = japanese ? enPattern : jaPattern;
    if (pattern.test(value)) {
      return `${leading}${value.replace(pattern, japanese ? jaReplacement : enReplacement)}${trailing}`;
    }
  }
  return source;
}

